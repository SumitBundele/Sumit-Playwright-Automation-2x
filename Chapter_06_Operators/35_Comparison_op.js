//Comparison operators compare two values and return a boolean result (true or false). Here are some common comparison operators in JavaScript:

//== (Equal to)
console.log(5 == '5'); // Output: true (loose equality, type coercion occurs)

//>,<,>=,<=,=,==,===,!=,!==

//=== (Strict equal to)
console.log(5 === '5'); // Output: false (strict equality, no type coercion)
//== (Equal to)
console.log(5 == '5'); // Output: true (loose equality, type coercion occurs)
//= (Assignment operator)
let x = 5;

console.log(3 > 2); // Output: true
console.log(3 < 2); // Output: false
console.log(3 >= 4);//3<4 = true or 3=4 false // Output: false
console.log(3 <= 2); // Output: false
console.log(3 == '3');  // Output: true (loose equality, type coercion occurs)
console.log(3 === '3'); // Output: false (strict equality, no type coercion)
console.log(3 != '3'); // Output: false (loose inequality, type coercion occurs)
console.log(3 !== '3'); // Output: true (strict inequality, no type coercion)   