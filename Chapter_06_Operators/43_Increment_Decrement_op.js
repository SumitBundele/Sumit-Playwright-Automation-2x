// Pre Increment ++
//increase the value and the assign the value to a

let a = 10;
let i = ++a; // i is assigned the value of a (10)
console.log(a);
console.log(i);// Output: 11 (a is incremented before being logged)      

// Post Increment ++
let b = 5;
console.log(b++);   // Output: 5 (b is logged before being incremented)
console.log(b);     // Output: 6 (b is now incremented)

// Pre Decrement --
let c = 20;
console.log(--c); // Output: 19 (c is decremented before being logged)      
// Post Decrement --
let d = 15;
console.log(d--);   // Output: 15 (d is logged before being decremented)
console.log(d);     // Output: 14 (d is now decremented)

