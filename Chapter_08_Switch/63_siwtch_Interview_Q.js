let fruit = "Apple";

switch (fruit) {
    case "Mango":
        console.log("Mangoes are sweet");
    case "Apple":
        console.log("Apples are sweet");
    case "Banana":
        console.log("Bananas are sweet");
    case "Orange":
        console.log("Oranges are sweet");
    case "Grapes":
        console.log("Grapes are sweet");
    case "Pineapple":
        console.log("Pineapples are sweet");
    default:
        console.log("Unknown fruit");
}   
