//Arroew Function - ES6 -Ecma Script Version 6
//function as Expression 
const greet = function (name) {
    return name;
}
let result = greet("Vivan");
console.log(result);


//Arrow function
const greet2 = (name2) => name2;
let result2 = greet2("Sumit");
console.log(result2);

const double = n => n * 2;
console.log(double(20));
